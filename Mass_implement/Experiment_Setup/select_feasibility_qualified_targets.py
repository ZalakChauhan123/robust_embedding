"""Freeze a leakage-qualified UMLS Set B from an oversampled candidate pool.

The candidate pool is generated by ``prepare_umls_targets.py`` using a clean
victim checkpoint.  Its feasibility artifacts are generated by
``target_feasibility_check.py`` using the fixed attacker surrogate.  This
script applies the *same* held-out and Set-B overlap rules used by
``construct_poisoned_dataset.py`` before freezing the final target list.

It intentionally does not inspect poisoned-victim results.  Candidate order
comes from the seed-controlled pool so selection is deterministic and can be
reproduced before RQ1/RQ2 evaluation.
"""
from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from pathlib import Path
from typing import Any


MASS_DIR = Path(__file__).resolve().parents[1]
DATASET_DIR = MASS_DIR / "dataset_uml"

FINAL_FILES = (
    "set_B_target_triples.tsv",
    "set_B_provenance.csv",
    "target_setup_summary.json",
    "qualification_audit.csv",
)


Triple = tuple[str, str, str]


def read_triples(path: Path) -> list[Triple]:
    """Read a headerless, three-column TSV file."""
    if not path.is_file():
        raise FileNotFoundError(f"Missing triple file: {path}")
    triples: list[Triple] = []
    seen: set[Triple] = set()
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        for line_no, row in enumerate(csv.reader(handle, delimiter="\t"), 1):
            if not row or (len(row) == 1 and not row[0].strip()):
                continue
            triple = tuple(value.strip() for value in row)
            if len(triple) != 3 or not all(triple):
                raise ValueError(f"Invalid triple at {path}:{line_no}: {row!r}")
            if triple in seen:
                raise ValueError(f"Duplicate triple at {path}:{line_no}: {triple!r}")
            seen.add(triple)
            triples.append(triple)
    if not triples:
        raise ValueError(f"No triples found: {path}")
    return triples


def load_json(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise FileNotFoundError(f"Missing JSON file: {path}")
    value = json.loads(path.read_text(encoding="utf-8-sig"))
    if not isinstance(value, dict):
        raise ValueError(f"Expected JSON object: {path}")
    return value


def candidate_edges(candidate: dict[str, Any]) -> tuple[Triple, Triple]:
    edges: list[Triple] = []
    for field in ("first_triple", "second_triple"):
        raw = candidate.get(field)
        if not isinstance(raw, list) or len(raw) != 3 or not all(
            isinstance(value, str) and value.strip() for value in raw
        ):
            raise ValueError(f"Malformed candidate {field}: {raw!r}")
        edges.append(tuple(raw))
    return edges[0], edges[1]


def legal_path_count(
    paths: list[dict[str, Any]],
    target: Triple,
    *,
    train: set[Triple],
    held_out: set[Triple],
    final_targets: set[Triple],
) -> tuple[int, Counter[str]]:
    """Mirror the baseline constructor's complete-path legality filter."""
    rejected: Counter[str] = Counter()
    legal = 0
    for path in paths:
        if not isinstance(path, dict):
            rejected["invalid"] += 1
            continue
        try:
            first, second = candidate_edges(path)
        except ValueError:
            rejected["invalid"] += 1
            continue
        invalid = (
            path.get("has_self_loop", False)
            or first[0] == first[2]
            or second[0] == second[2]
            or first[2] != second[0]
            or first[0] != target[0]
            or second[2] != target[2]
            or (first in train and second in train)
        )
        if invalid:
            rejected["invalid"] += 1
        elif first in final_targets or second in final_targets:
            rejected["target_overlap"] += 1
        elif (first in held_out and first not in train) or (
            second in held_out and second not in train
        ):
            rejected["leakage"] += 1
        else:
            legal += 1
    return legal, rejected


def candidate_records(
    targets_file: Path,
    metadata_file: Path,
    feasibility_dir: Path,
    min_rank: float,
    max_rank: float,
) -> list[dict[str, Any]]:
    targets = read_triples(targets_file)
    metadata = load_json(metadata_file)
    source_rows = metadata.get("set_B_rows")
    if not isinstance(source_rows, list) or len(source_rows) != len(targets):
        raise ValueError("Candidate metadata rows do not match candidate targets")

    summary = load_json(feasibility_dir / "feasibility_summary.json")
    feasibility_rows = summary.get("targets")
    if not isinstance(feasibility_rows, list) or len(feasibility_rows) != len(targets):
        raise ValueError("Candidate feasibility rows do not match candidate targets")
    if summary.get("error_targets", 0):
        raise ValueError("Candidate feasibility run contains errors")

    records: list[dict[str, Any]] = []
    for index, target in enumerate(targets, 1):
        source = source_rows[index - 1]
        status = feasibility_rows[index - 1]
        target_id = f"target_{index:03d}"
        if tuple(source.get("target_triple", ())) != target:
            raise ValueError(f"Candidate metadata mismatch at {target_id}")
        if status.get("target_id") != target_id or tuple(
            status.get(field, "") for field in ("head", "relation", "tail")
        ) != target:
            raise ValueError(f"Candidate feasibility mismatch at {target_id}")
        rank = source.get("clean_filtered_tail_rank")
        if not isinstance(rank, (int, float)):
            raise ValueError(f"Missing clean-victim rank at {target_id}")
        result = load_json(feasibility_dir / f"{target_id}.json")
        if tuple(result.get("target_triple", ())) != target:
            raise ValueError(f"Candidate feasibility payload mismatch at {target_id}")
        paths = result.get("ranked_candidate_paths")
        if not isinstance(paths, list):
            paths = []
        original = source.get("original_test_triple")
        if not isinstance(original, list) or len(original) != 3:
            original = ["", "", ""]
        records.append({
            "source_target_id": target_id,
            "source_index": index,
            "target": target,
            "rank": float(rank),
            "source_status": str(status.get("status", "")),
            "paths": paths,
            "original_test_triple": tuple(original),
            "rank_in_requested_band": min_rank <= float(rank) <= max_rank,
        })
    return records


def select_targets(
    records: list[dict[str, Any]],
    *,
    num_targets: int,
    train: set[Triple],
    held_out: set[Triple],
) -> tuple[list[dict[str, Any]], dict[str, dict[str, Any]]]:
    """Greedily retain source-ordered candidates without invalidating prior paths."""
    selected: list[dict[str, Any]] = []
    audit: dict[str, dict[str, Any]] = {}
    for record in records:
        source_id = record["source_target_id"]
        if not record["rank_in_requested_band"]:
            audit[source_id] = {"decision": "rejected", "reason": "outside_rank_band"}
            continue
        if record["source_status"] != "feasible" or not record["paths"]:
            audit[source_id] = {"decision": "rejected", "reason": "no_preliminary_candidate_path"}
            continue

        proposed = selected + [record]
        proposed_targets = {item["target"] for item in proposed}
        path_counts: dict[str, int] = {}
        for item in proposed:
            count, _ = legal_path_count(
                item["paths"], item["target"], train=train,
                held_out=held_out, final_targets=proposed_targets,
            )
            path_counts[item["source_target_id"]] = count
        if not all(path_counts.values()):
            audit[source_id] = {
                "decision": "rejected",
                "reason": "would_remove_legal_path_from_final_set",
                "legal_paths_if_added": path_counts[source_id],
            }
            continue

        selected.append(record)
        audit[source_id] = {
            "decision": "selected",
            "reason": "rank_and_final_leakage_qualified",
            "legal_paths_if_added": path_counts[source_id],
        }
        if len(selected) == num_targets:
            break

    final_targets = {item["target"] for item in selected}
    for item in selected:
        count, rejected = legal_path_count(
            item["paths"], item["target"], train=train,
            held_out=held_out, final_targets=final_targets,
        )
        if count < 1:
            raise AssertionError(f"Final selection is not leakage-qualified: {item['source_target_id']}")
        audit[item["source_target_id"]].update({
            "legal_paths_in_final_set": count,
            "final_rejections": dict(rejected),
        })
    return selected, audit


def write_outputs(
    output_dir: Path,
    selected: list[dict[str, Any]],
    records: list[dict[str, Any]],
    audit: dict[str, dict[str, Any]],
    *,
    source_targets: Path,
    source_metadata: Path,
    source_feasibility: Path,
    checkpoint: str,
    min_rank: float,
    max_rank: float,
    requested: int,
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    with (output_dir / "set_B_target_triples.tsv").open("w", encoding="utf-8", newline="") as handle:
        csv.writer(handle, delimiter="\t", lineterminator="\n").writerows(
            item["target"] for item in selected
        )

    provenance_fields = [
        "target_id", "source_target_id", "source_index", "original_head", "relation",
        "original_tail", "target_head", "target_tail", "clean_filtered_tail_rank",
        "legal_paths_in_final_set",
    ]
    with (output_dir / "set_B_provenance.csv").open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=provenance_fields)
        writer.writeheader()
        for index, item in enumerate(selected, 1):
            head, relation, tail = item["target"]
            original_head, _, original_tail = item["original_test_triple"]
            writer.writerow({
                "target_id": f"target_{index:03d}",
                "source_target_id": item["source_target_id"],
                "source_index": item["source_index"],
                "original_head": original_head,
                "relation": relation,
                "original_tail": original_tail,
                "target_head": head,
                "target_tail": tail,
                "clean_filtered_tail_rank": item["rank"],
                "legal_paths_in_final_set": audit[item["source_target_id"]]["legal_paths_in_final_set"],
            })

    summary = {
        "experiment": "UMLS feasibility-qualified MaSS Set B target selection",
        "selection_rule": (
            "clean seed-42 victim filtered tail rank in requested band and at least one "
            "complete candidate path legal under train/valid/test/Set-B leakage rules"
        ),
        "requested_set_B_size": requested,
        "actual_set_B_size": len(selected),
        "clean_victim_rank_band": [min_rank, max_rank],
        "candidate_sources": {
            "targets": str(source_targets),
            "metadata": str(source_metadata),
            "feasibility_dir": str(source_feasibility),
            "clean_victim_checkpoint": checkpoint,
        },
        "all_targets_absent_from_original_train_valid_test": True,
        "set_B_rows": [
            {
                "target_id": f"target_{index:03d}",
                "source_target_id": item["source_target_id"],
                "original_test_triple": list(item["original_test_triple"]),
                "target_triple": list(item["target"]),
                "clean_filtered_tail_rank": item["rank"],
                "legal_paths_in_final_set": audit[item["source_target_id"]]["legal_paths_in_final_set"],
            }
            for index, item in enumerate(selected, 1)
        ],
    }
    (output_dir / "target_setup_summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8"
    )

    audit_fields = [
        "source_target_id", "source_index", "head", "relation", "tail", "rank",
        "source_status", "decision", "reason", "legal_paths_if_added",
        "legal_paths_in_final_set", "final_rejections",
    ]
    with (output_dir / "qualification_audit.csv").open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=audit_fields)
        writer.writeheader()
        for record in records:
            item_audit = audit.get(record["source_target_id"], {
                "decision": "not_examined", "reason": "target_count_already_reached"
            })
            head, relation, tail = record["target"]
            writer.writerow({
                "source_target_id": record["source_target_id"],
                "source_index": record["source_index"],
                "head": head,
                "relation": relation,
                "tail": tail,
                "rank": record["rank"],
                "source_status": record["source_status"],
                **{
                    key: json.dumps(value, sort_keys=True) if isinstance(value, dict) else value
                    for key, value in item_audit.items()
                },
            })


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Freeze rank-qualified, leakage-qualified UMLS MaSS Set B targets"
    )
    parser.add_argument("--candidate-targets", type=Path, required=True)
    parser.add_argument("--candidate-metadata", type=Path, required=True)
    parser.add_argument("--candidate-feasibility-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--num-targets", type=int, default=100)
    parser.add_argument("--min-rank", type=float, default=11.0)
    parser.add_argument("--max-rank", type=float, default=30.0)
    parser.add_argument("--clean-victim-checkpoint", type=Path, required=True)
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()

    if args.num_targets < 1:
        raise ValueError("--num-targets must be positive")
    if not 1 <= args.min_rank <= args.max_rank:
        raise ValueError("Invalid rank band")
    if not args.clean_victim_checkpoint.is_file():
        raise FileNotFoundError(f"Missing clean victim checkpoint: {args.clean_victim_checkpoint}")
    if not args.overwrite and any((args.output_dir / name).exists() for name in FINAL_FILES):
        raise FileExistsError("Output already exists; choose a new directory or pass --overwrite")

    train = set(read_triples(DATASET_DIR / "train.txt"))
    held_out = set(read_triples(DATASET_DIR / "valid.txt")) | set(
        read_triples(DATASET_DIR / "test.txt")
    )
    records = candidate_records(
        args.candidate_targets,
        args.candidate_metadata,
        args.candidate_feasibility_dir,
        args.min_rank,
        args.max_rank,
    )
    selected, audit = select_targets(
        records, num_targets=args.num_targets, train=train, held_out=held_out
    )
    if len(selected) != args.num_targets:
        raise ValueError(
            f"Only {len(selected)}/{args.num_targets} candidates satisfy final qualification; "
            "generate a larger candidate pool."
        )
    selected_set = {item["target"] for item in selected}
    if selected_set & (train | held_out):
        raise AssertionError("Selected Set B overlaps original UMLS facts")
    write_outputs(
        args.output_dir,
        selected,
        records,
        audit,
        source_targets=args.candidate_targets,
        source_metadata=args.candidate_metadata,
        source_feasibility=args.candidate_feasibility_dir,
        checkpoint=str(args.clean_victim_checkpoint),
        min_rank=args.min_rank,
        max_rank=args.max_rank,
        requested=args.num_targets,
    )
    print(f"Selected {len(selected)} feasibility-qualified targets")
    print(f"Saved: {args.output_dir.resolve()}")


if __name__ == "__main__":
    main()
