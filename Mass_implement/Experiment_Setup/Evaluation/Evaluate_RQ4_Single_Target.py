#!/usr/bin/env python3
"""Evaluate the first Table 5 MaSS example alone on TransE and TransH.

Reuse the saved target_003 two-edge path, inject ONLY its two new facts, and
train paired clean/poisoned victims. Never change the final RQ1 table.
"""
from __future__ import annotations

import argparse
import contextlib
import csv
import hashlib
import json
import math
import sys
import textwrap
import time
from pathlib import Path

MASS = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(MASS))
sys.path.insert(0, str(MASS / "Experiment_Setup"))
import torch
from train_victim_models import run as train_transe
from train_shallow_victim_models import run as train_transh
from Evaluate_victim_models import run as evaluate_transe
from Evaluate_shallow_victim_models import run as evaluate_transh

EXP = MASS / "outputs" / "Experiments" / "UMLS_feasible_rank11_15_seed42"
DATA = MASS / "dataset_uml"
ROOT = EXP / "RQ4" / "single_target_transe_transh_target003"
FINAL = MASS / "outputs" / "Final Results" / "RQ - 4"
RQ1 = MASS / "outputs" / "Final Results" / "RQ-1 -- Attack Effectiveness -- Final Results.csv"
STEM = "RQ-4 -- Single Target Experiment (TransE and TransH)"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2), encoding="utf-8")


def read_triples(path):
    with path.open(encoding="utf-8-sig", newline="") as stream:
        triples = [tuple(row) for row in csv.reader(stream, delimiter="\t") if row]
    if not triples or any(len(row) != 3 for row in triples) or len(set(triples)) != len(triples):
        raise ValueError(f"Invalid or duplicate triples: {path}")
    return triples


def write_triples(path, triples):
    with path.open("w", encoding="utf-8", newline="") as stream:
        csv.writer(stream, delimiter="\t", lineterminator="\n").writerows(triples)


def verify(hashes):
    for name, expected in hashes.items():
        if digest(Path(name)) != expected:
            raise ValueError(f"Protected input or artifact changed: {name}")


def export(summary):
    FINAL.mkdir(parents=True, exist_ok=True)
    rows = summary["results"]
    with (FINAL / f"{STEM}.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    write_json(FINAL / f"{STEM}.json", summary)
    target = "(" + ", ".join(summary["target_triple"]) + ")"
    facts = ["(" + ", ".join(edge) + ")" for edge in summary["poisoned_triplets"]]
    lines = ["# UMLS: single-target MaSS experiment", "", f"Target: `{target}`", "",
             "Only these two supporting triplets were injected:", "",
             *[f"{i}. `{fact}`" for i, fact in enumerate(facts, 1)], "",
             "| Model | State | Filtered tail rank | Hit@10 | MRR |", "|---|---|---:|---:|---:|"]
    for row in rows:
        lines.append(f"| {row['model']} | {row['state']} | {row['rank']:g} | {row['Hit_at_10']:.0f} | {row['MRR']:.6f} |")
    lines += ["", "Both models: dimension 128, 500 epochs, batch size 256, Adam learning rate 0.01, margin 1, seed 42.",
              "Clean training: 5,216 facts. Poisoned training: 5,218 facts. All 135 entities are ranked; known original facts are filtered, with average ranks for ties.",
              "One target: Hit@10 = 1 if rank <= 10, otherwise 0; MRR = 1/rank. These are single-example results, not aggregate model performance.",
              "Source: the first previously selected Table 5 example, original target_003; local evaluator ID target_001. No target was chosen by observed attack success.",
              "The saved path was generated by the original 64-dimensional TransE attacker surrogate. The same two injections are used for both victims.",
              "This run reuses the existing local TransH implementation, including its vector normalization rules.",
              "The generated target and supporting triplets are poisoning examples, not verified biomedical assertions.",
              f"Raw models, loss histories, rank files and provenance: `{ROOT}`", "The final RQ1 CSV is unchanged."]
    (FINAL / f"{STEM}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig = plt.figure(figsize=(11.8, 5.4))
    fig.text(.5, .95, "UMLS — Single-target MaSS experiment", ha="center", fontsize=15, weight="bold")
    fig.text(.04, .86, f"Target: {target}", fontsize=11, family="DejaVu Sans Mono")
    fig.text(.04, .79, "Poisoned triplets (same two injections for both models):", fontsize=11, weight="bold")
    for y, number, fact in zip((.71, .63), (1, 2), facts):
        fig.text(.04, y, textwrap.fill(f"{number}. {fact}", width=100, break_long_words=False, break_on_hyphens=False),
                 fontsize=10.5, family="DejaVu Sans Mono", va="center")
    ax = fig.add_axes((.06, .20, .88, .34))
    ax.axis("off")
    cells = [[r["model"], r["state"], f"{r['rank']:g}", f"{r['Hit_at_10']:.0f}", f"{r['MRR']:.6f}"] for r in rows]
    table = ax.table(cellText=cells, colLabels=["Model", "State", "Filtered tail rank", "Hit@10", "MRR"],
                     cellLoc="center", loc="center", colWidths=[.16, .20, .25, .16, .20])
    table.auto_set_font_size(False)
    table.set_fontsize(11)
    table.scale(1, 1.6)
    for (r, _), cell in table.get_celld().items():
        cell.set_linewidth(.5)
        if r == 0:
            cell.set_facecolor("#e9eef3")
            cell.set_text_props(weight="bold")
    fig.text(.04, .105, "Both victims: 128 dimensions; 500 epochs; Adam lr 0.01; batch 256; margin 1; seed 42.", fontsize=9)
    fig.text(.04, .065, "One target: Hit@10 is 0 or 1; MRR = 1/rank. Training graph: 5,216 clean → 5,218 poisoned facts.", fontsize=9)
    try:
        for extension in ("png", "pdf"):
            fig.savefig(FINAL / f"{STEM}.{extension}", dpi=300, bbox_inches="tight")
    finally:
        plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--resume", action="store_true")
    args = parser.parse_args()
    torch.set_num_threads(1)
    torch.set_num_interop_threads(1)
    source = EXP / "baseline" / "poisoning" / "selected_poisoning_paths.json"
    files = [source, RQ1, Path(__file__).resolve(),
             MASS / "Experiment_Setup" / "train_victim_models.py",
             MASS / "Experiment_Setup" / "train_shallow_victim_models.py",
             Path(__file__).with_name("Evaluate_victim_models.py"),
             Path(__file__).with_name("Evaluate_shallow_victim_models.py"),
             MASS / "Path_Generation_Module" / "TransE_Surrogate.py",
             MASS / "Path_Generation_Module" / "TransE_Victim.py",
             MASS / "Path_Generation_Module" / "TransH_Victim.py",
             EXP / "baseline" / "poisoning" / "injected_triples.tsv"]
    files += [DATA / name for name in ("train.txt", "valid.txt", "test.txt", "entities.txt", "relations.txt")]
    hashes = {str(p): digest(p) for p in files}
    chosen = next(x for x in read_json(source)["targets"] if x["target_id"] == "target_003")
    target = tuple(chosen["target_triple"])
    selected = chosen["stealthiness"]["selected_candidate_paths"]
    if len(selected) != 1:
        raise ValueError("Expected one complete saved two-edge path")
    pair = [tuple(selected[0][key]) for key in ("first_triple", "second_triple")]
    clean = read_triples(DATA / "train.txt")
    known = set(clean) | set(read_triples(DATA / "valid.txt")) | set(read_triples(DATA / "test.txt"))
    all_targets = set(read_triples(EXP / "setup" / "set_B_target_triples.tsv"))
    if (len(set(pair)) != 2 or target in known or set(pair) & (known | all_targets)
            or set(pair) != {tuple(x) for x in chosen["new_to_global_training"]}
            or not set(pair) <= set(read_triples(EXP / "baseline" / "poisoning" / "injected_triples.tsv"))):
        raise ValueError("Saved target/path integrity check failed")
    ROOT.mkdir(parents=True, exist_ok=True)
    config = {"original_target_id": "target_003", "local_target_id": "target_001",
              "target_triple": target, "poisoned_triplets": pair, "input_sha256": hashes,
              "victim_parameters": {"dim": 128, "epochs": 500, "batch_size": 256, "lr": .01, "margin": 1., "seed": 42},
              "selection": "First Table 5 example; selected before measuring single-target victim outcomes.",
              "source_sampling_seed": chosen["sampling_seed"], "path_rank": selected[0]["rank"]}
    config_path = ROOT / "experiment_config.json"
    if config_path.exists():
        if not args.resume or read_json(config_path) != json.loads(json.dumps(config)):
            raise ValueError("Output exists; use --resume with unchanged configuration and inputs")
    else:
        write_json(config_path, config)
    poison = ROOT / "poisoning"
    poison.mkdir(exist_ok=True)
    if not (poison / "poisoned_train.txt").exists():
        write_triples(ROOT / "target_triple.tsv", [target])
        write_triples(poison / "injected_triples.tsv", pair)
        write_triples(poison / "poisoned_train.txt", clean + pair)
        with (poison / "poisoning_summary.csv").open("w", newline="", encoding="utf-8") as stream:
            writer = csv.writer(stream)
            writer.writerow(["target_id", "head", "relation", "tail", "status", "injected_for_target"])
            writer.writerow(["target_001", *target, "injected", 2])
        write_json(poison / "poisoning_summary.json", {"method": "MaSS saved single-target path", **config})
    results = []
    for model in ("TransE", "TransH"):
        verify(hashes)
        point = ROOT / model
        point.mkdir(exist_ok=True)
        manifest = point / "stage_manifest.json"
        train_dir, eval_dir = point / "victim_models", point / "evaluation"
        if manifest.exists():
            verify(read_json(manifest)["artifact_sha256"])
        else:
            train_args = argparse.Namespace(
                clean_train=DATA / "train.txt", poisoned_train=poison / "poisoned_train.txt",
                injected=poison / "injected_triples.tsv", valid=DATA / "valid.txt", test=DATA / "test.txt",
                targets=ROOT / "target_triple.tsv", entities=DATA / "entities.txt", relations=DATA / "relations.txt",
                output_dir=train_dir, attack_name="MaSS single-target", epochs=500, dim=128,
                batch_size=256, lr=.01, margin=1., seed=42, log_every=50, overwrite=False,
                model=model, transh_lr=.01, transh_margin=1., distmult_lr=.001, label_smoothing=.1)
            eval_args = argparse.Namespace(
                clean_checkpoint=train_dir / f"clean_{model.lower()}.pt",
                poisoned_checkpoint=train_dir / f"poisoned_{model.lower()}.pt",
                train=train_args.clean_train, poisoned_train=train_args.poisoned_train,
                injected=train_args.injected, valid=train_args.valid, test=train_args.test, targets=train_args.targets,
                poisoning_summary=poison / "poisoning_summary.csv", training_summary=train_dir / "training_summary.json",
                output_dir=eval_dir, attack_name=train_args.attack_name, overwrite=False,
                model=model, deeppath_eval_batch_size=4)
            print(f"{model}: training clean/poisoned 128-dimensional victims for one target...", flush=True)
            start = time.perf_counter()
            with (point / "run.log").open("w", encoding="utf-8") as log:
                with contextlib.redirect_stdout(log), contextlib.redirect_stderr(log):
                    (train_transe if model == "TransE" else train_transh)(train_args)
                    (evaluate_transe if model == "TransE" else evaluate_transh)(eval_args)
            artifacts = [p for d in (train_dir, eval_dir) for p in d.iterdir() if p.is_file()]
            write_json(manifest, {"elapsed_seconds": time.perf_counter() - start,
                                 "artifact_sha256": {str(p): digest(p) for p in artifacts}})
        training = read_json(train_dir / "training_summary.json")
        if (training["datasets"]["poisoned_training_triples"] != 5218
                or training["datasets"]["unique_injected_triples"] != 2
                or not training["same_initial_embeddings_verified"]):
            raise ValueError("Training controls failed")
        with (eval_dir / "set_B_target_rank_comparison.csv").open(encoding="utf-8-sig", newline="") as stream:
            rank_rows = list(csv.DictReader(stream))
        metrics = read_json(eval_dir / "set_B_attack_metrics.json")["set_B_all_targets"]
        if len(rank_rows) != 1 or tuple(rank_rows[0][k] for k in ("head", "relation", "tail")) != target:
            raise ValueError("Single-target evaluator changed target or denominator")
        for state in ("clean", "poisoned"):
            rank = float(rank_rows[0][f"{state}_rank"])
            hit, mrr = int(rank <= 10), 1 / rank
            if not math.isclose(mrr, metrics[state]["MRR"]) or hit != metrics[state]["Hits@10"]:
                raise ValueError("Single-target metrics disagree with rank")
            results.append({"model": model, "state": state, "rank": rank, "Hit_at_10": hit, "MRR": mrr})
        print(f"{model}: {json.dumps(results[-2:])}", flush=True)
    verify(hashes)
    summary = {**config, "results": results, "clean_training_triples": len(clean), "poisoned_training_triples": len(clean) + 2,
               "number_of_targets": 1, "ranking": "Filtered tail prediction over 135 entities; original train/valid/test facts; average ties.",
               "RQ1_final_csv_unchanged": True, "raw_output_directory": str(ROOT)}
    write_json(ROOT / "results_summary.json", summary)
    export(summary)
    verify(hashes)
    print(f"Saved readable results: {FINAL / STEM}", flush=True)
    print(f"Raw artifacts: {ROOT}", flush=True)


if __name__ == "__main__":
    main()
